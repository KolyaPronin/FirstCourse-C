//// **  Это необходимо для того, чтобы привести матрицу к верхнетреугольному виду
//// путем вычитания кратного первого уравнения из последующих уравнений.
//
//
//// *** допустим у нас есть такая матрица
////   2  1 -1  | 8 
////  -3 -1  2  |-11
////  -2  1  2  |-3
////
////  ведущий элемент находится в первой строке и это 2 и нам надо обнулить элементы под 2
////  для этого мы используем соотношение relation  которое равно отношению элемента в текущей строке к ведущему элементу 
////  в нашем случае это отношение элемента к 2
////  Затем мы умножаем это отношение на каждый элемент под ведущим элементом и вычитаем его из 
////  соответствующего элемента в строке j (в данном случае, это умножение на relation и вычитание из второго и третьего уравнений).
////
//// применим это процесс к системе выше.
//// 1) Первую строку  мы не трогаем
//// 2) вторая строка:
//// relation = -3 / 2
//// Мы вычитаем 2 * relation из y (то есть -1) и -1 * relation из z (то есть -2).
//// 
//// Во втором уравнении мы нашли, что коэффициент перед y должен быть уменьшен
//// на 2 * relation, а коэффициент перед z должен быть уменьшен на (-1) * relation.
//// 
//// Таким образом, когда relation равно (-3) / 2:
//// 
//// Мы вычитаем из y значение (-1) * relation = (-1) * (-3/2) = 3/2.
//// Мы вычитаем из z значение(-1)* relation = (-1) * (-3 / 2) = 3 / 2.
//// 
//// 
//// 
//// 3) третья строка:
//// relation = (-2) / 2 (коэффициент перед x в третьем уравнении делится на ведущий элемент в первом уравнении)
//// Мы вычитаем 2 * relation из y(то есть 1) и - 1 * relation из z(то есть - 2).
////
////
////
