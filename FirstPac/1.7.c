//// matrix[j][n] обращается к элементу матрицы в строке j и столбце n. В данном случае n является индексом столбца, где находятся правые части уравнений в расширенной матрице (то есть столбец справа от вертикальной черты в расширенной матрице).
//// matrix[j][i] - это элемент матрицы в строке j и столбце i.Это элемент матрицы коэффициентов, находящийся на диагонали или ведущий элемент текущей строки.
